export const getProductById = (id) =>
  products.find((item) => String(item.id) === String(id));

export const getFeaturedProducts = () => products.filter((item) => item.featured);

export const getDiscountedProducts = () =>
  products
    .filter((item) => item.oldPrice && item.oldPrice > item.price)
    .map((item) => ({
      ...item,
      discount: Math.round(((item.oldPrice - item.price) / item.oldPrice) * 100),
    }));

export const formatPrice = (value) =>
  `FRW ${Number(value || 0).toLocaleString(undefined, {
    minimumFractionDigits: 0,
    maximumFractionDigits: 2,
  })}`;

